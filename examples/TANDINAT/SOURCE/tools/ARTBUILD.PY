#!/usr/bin/env python3
"""Exact sprite slicing and BMP/DIB packing. Never resample or redraw source art."""
from pathlib import Path
from PIL import Image
import hashlib,json,struct
P=Path(__file__).resolve().parents[1]
PALETTE=[(0,0,0),(0,0,170),(0,170,0),(0,170,170),(170,0,0),(170,0,170),(170,85,0),(170,170,170),(85,85,85),(85,85,255),(85,255,85),(85,255,255),(255,85,85),(255,85,255),(255,255,85),(255,255,255)]
# Source crops remain 1:1. Black padding is outside their native rectangles.
CROPS=[('idle body','CABINET.PNG',(16,16,112,134),(0,2)),
 ('idle crown cap','CABINET.PNG',(60,14,66,16),(44,0)),
 ('speak body','CABINET.PNG',(114,16,210,134),(0,122)),
 ('speak crown cap','CABINET.PNG',(158,14,163,16),(44,120)),
 ('fortune body','CABINET.PNG',(212,16,308,134),(0,242)),
 ('fortune crown cap','CABINET.PNG',(254,14,259,16),(42,240)),
 ('title','CABINET.PNG',(103,0,229,14),(0,360)),
 ('title lower left','CABINET.PNG',(103,14,134,16),(0,374)),
 ('title lower right','CABINET.PNG',(181,14,213,16),(78,374)),
 ('wink','PARTS.PNG',(269,28,317,68),(0,376)),
 ('think','PARTS.PNG',(59,88,107,128),(48,376))]
atlas=Image.new('RGB',(128,416));report=[]
for name,file,rect,at in CROPS:
 im=Image.open(P/'art'/file).convert('RGB');sprite=im.crop(rect);atlas.paste(sprite,at)
 assert atlas.crop((at[0],at[1],at[0]+sprite.width,at[1]+sprite.height)).tobytes()==sprite.tobytes()
 report.append({'name':name,'source':file,'source_rectangle':rect,'atlas_xy':at,'pixel_exact':True})
indices=[PALETTE.index(p) for p in atlas.getdata()]
bits=bytes(indices[y*128+x]*16+indices[y*128+x+1] for y in range(415,-1,-1) for x in range(0,128,2))
header='/* Generated by ARTBUILD.PY: immutable source crops, native 4bpp DIB. */\n#define ART_W 128\n#define ART_H 416\nstatic unsigned char artbits[26624]={\n'+''.join(','.join(str(v) for v in bits[i:i+32])+',\n' for i in range(0,len(bits),32))+'};\n'
(P/'src/ART.H').write_bytes(header.replace('\n','\r\n').encode('ascii'))
atlas.save(P/'art/ATLAS.PNG')
report={'source_sha256':{p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in [P/'art/CABINET.PNG',P/'art/PARTS.PNG']},'crops':report,'atlas_size':[128,416],'dib_bytes':len(bits),'palette_exact':True,'generation':'Exact crop, black padding and lossless 4-bit index packing. Neighboring title/crown pixels are separated by non-overlapping crop slices. No smoothing, resampling or generated artwork.'}
(P/'art/MANIFEST.JSON').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps(report,indent=2))
