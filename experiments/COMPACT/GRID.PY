def accented(char):
    """Authored narrow accent recipe, without scaling the body grid."""
    import unicodedata
    parts = unicodedata.normalize('NFD', char or '')
    if len(parts) != 2 or parts[0] not in G:
        return None
    accents = {
        '\u0300': ('#..', '.#.'), '\u0301': ('..#', '.#.'),
        '\u0302': ('.#.', '#.#'), '\u0303': ('.#.', '#.#'),
        '\u0308': ('#.#', '...'), '\u030a': ('.#.', '#.#'),
        '\u030c': ('#.#', '.#.'),
        '\u0327': ('...', '...'),
    }
    if parts[1] not in accents:
        return None
    rows = FIXED.get(parts[0], G[parts[0]])
    if len(rows[0]) > 3:
        return None
    rows = [r.ljust(3, '.') for r in rows]
    if parts[1] == '\u0327':
        return rows[:7] + ['.#.']
    # Lowercase's authored body starts at row 2, leaving two accent rows.
    # Uppercase keeps six original body rows and a single explicit accent.
    return list(accents[parts[1]]) + rows[2:] if parts[0].islower() else [accents[parts[1]][0]] + rows[1:]
