#!/usr/bin/env python3
"""Generate P15SHOW.ASM from the exact text PC1512.DRV is built with.

Usage:
  python3 src/pc1512/P15TEST.PY --emit <dir>     writes <dir>/P15SHOW.ASM
  then build it like the other DOS tools:
  python3 src/pcjr/BUILDCOM.PY --deps <inputs> --dosbox <dosbox-x> \
      --out <fresh-dir> --src <dir>/P15SHOW.ASM

P15SHOW.COM runs the driver's enable sequence (P15PATCH.P15_MODE: ROS mode 6,
flyback wait, 3D9h/3DDh/3DEh), then for each of the 200 rows the driver's own
CGA row-address text (P15PATCH.cga_row) and p15_row macro, copying a 320-byte
shadow row built in DOS memory: 16 vertical bars, 40 pixels each, in colour
order 0..15. Any key runs the driver's disable sequence and returns to mode
3. On a PC1512 or 86Box's PC1512 the bars must decode to exactly colours
0..15; P15PATCH --check proves the same copy against 86Box's decoder on the
host. Nothing is fetched.
"""
import argparse
import importlib.machinery
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
P15 = importlib.machinery.SourceFileLoader("p15patch", str(HERE / "P15PATCH.PY")).load_module()


def asm_text():
    head = (
        "; P15SHOW.ASM - generated by src/pc1512/P15TEST.PY from P15PATCH text.\r\n"
        ".8086\r\ncode segment para public 'CODE'\r\n"
        "assume cs:code,ds:code,es:code,ss:code\r\norg 100h\r\nentry: jmp start\r\n"
        "row     db 320 dup (0)\r\n"
        "rowno   dw 0\r\n"
    )
    build_row = (
        "; Shadow row: plane k (R,G,B,I) at +80k; bar c spans bytes 5c..5c+4.\r\n"
        "build_row proc near\r\n"
        "    xor bx,bx                 ; colour c\r\n"
        "br_colour:\r\n"
        "    mov di,bx\r\n    shl di,1\r\n    shl di,1\r\n    add di,bx      ; 5c\r\n"
        "    add di,offset row\r\n"
        "    test bl,4\r\n    jz br_g\r\n    mov byte ptr [di],0ffh\r\n    mov byte ptr [di+1],0ffh\r\n"
        "    mov byte ptr [di+2],0ffh\r\n    mov byte ptr [di+3],0ffh\r\n    mov byte ptr [di+4],0ffh\r\n"
        "br_g:\r\n    add di,80\r\n"
        "    test bl,2\r\n    jz br_b\r\n    mov byte ptr [di],0ffh\r\n    mov byte ptr [di+1],0ffh\r\n"
        "    mov byte ptr [di+2],0ffh\r\n    mov byte ptr [di+3],0ffh\r\n    mov byte ptr [di+4],0ffh\r\n"
        "br_b:\r\n    add di,80\r\n"
        "    test bl,1\r\n    jz br_i\r\n    mov byte ptr [di],0ffh\r\n    mov byte ptr [di+1],0ffh\r\n"
        "    mov byte ptr [di+2],0ffh\r\n    mov byte ptr [di+3],0ffh\r\n    mov byte ptr [di+4],0ffh\r\n"
        "br_i:\r\n    add di,80\r\n"
        "    test bl,8\r\n    jz br_next\r\n    mov byte ptr [di],0ffh\r\n    mov byte ptr [di+1],0ffh\r\n"
        "    mov byte ptr [di+2],0ffh\r\n    mov byte ptr [di+3],0ffh\r\n    mov byte ptr [di+4],0ffh\r\n"
        "br_next:\r\n    inc bx\r\n    cmp bx,16\r\n    jb br_colour\r\n    ret\r\nbuild_row endp\r\n"
    )
    main = (
        "start:\r\n    push cs\r\n    pop ds\r\n    cld\r\n    call build_row\r\n"
        + P15.P15_MODE +
        "    mov ax,0b800h\r\n    mov es,ax\r\n    mov rowno,0\r\n"
        "show_row:\r\n"
        + P15.cga_row("rowno") +
        "    mov si,offset row\r\n    mov bx,80\r\n    p15_row\r\n"
        "    inc rowno\r\n    cmp rowno,200\r\n    jae show_done\r\n    jmp show_row\r\n"
        "show_done:\r\n    xor ah,ah\r\n    int 16h\r\n"
        + P15.DISABLE_NEW.replace(P15.DISABLE_OLD, "") +
        "    mov ax,3\r\n    int 10h\r\n    mov ax,4c00h\r\n    int 21h\r\n"
    )
    return head + P15.ROW_MACROS + build_row + main + "code ends\r\nend entry\r\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--emit", type=Path, required=True)
    a = ap.parse_args()
    a.emit.mkdir(parents=True, exist_ok=True)
    (a.emit / "P15SHOW.ASM").write_bytes(asm_text().encode("latin-1"))
    print("P15TEST: wrote", a.emit / "P15SHOW.ASM")
    return 0


if __name__ == "__main__":
    sys.exit(main())
