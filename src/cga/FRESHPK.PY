"""Build/package an additive DOS launcher and one closed fresh CGA640 OEM kit.

Developer Python only. Accepted CGA/Tandy packets are never rewritten.
"""
import argparse,hashlib,json,os,shutil,struct,subprocess,zipfile,zlib
from pathlib import Path
HERE=Path(__file__).resolve().parent
BASE='downloads/COMPACT/CGA.ZIP'
BASE_PIN=dict(bytes=297312,sha256='84a1992803d1bd022318ddb001490b66494aba1e61ca09eef2fbc445fb469cc4')
SUPPORT=('CGA640.DRV','XTCSYS.FON','XTCFIX.FON','XTCOEM.FON','CGAGRAB.GR2',
         'XTSTATIC.LGO','WXTSPL01.RLE','FONTLIC.TXT','LOGOLIC.TXT','NOTICE.TXT')

def identity(b):return dict(bytes=len(b),sha256=hashlib.sha256(b).hexdigest())
def crlf(b):return b.replace(b'\r\n',b'\n').replace(b'\n',b'\r\n')
def save(p,b):p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(b)
def receipt(p,data):save(p,crlf((json.dumps(data,indent=2)+'\n').encode()))

def inputs(repo):
    data=(repo/BASE).read_bytes()
    if identity(data)!=BASE_PIN:raise ValueError('Exact current compact CGA base required')
    with zipfile.ZipFile(repo/BASE) as z:
        if z.testzip():raise ValueError('CGA base ZIP failed CRC')
        original={n:z.read(n) for n in z.namelist()}
    fresh={n:original['CGA/'+n] for n in SUPPORT}
    fresh['OEMSETUP.INF']=crlf((HERE/'FRESH.INF').read_bytes())
    return original,fresh

def sources(repo):
    _,fresh=inputs(repo)
    rows=['/* Generated by FRESHPK.PY from the closed fresh OEM inventory. */',
          'static const FRESHPIN fresh_files[]={']
    for n,b in sorted(fresh.items()):rows.append('{"%s",%dUL,0x%08xUL},'%(n,len(b),zlib.crc32(b)))
    rows+=['};','#define FRESH_COUNT %d'%len(fresh)]
    return {'FRESH.C':crlf((HERE/'FRESH.C').read_bytes()),
            'CRCFAST.H':(repo/'tools/DOSINST/CRCFAST.H').read_bytes(),
            'FRESHID.H':crlf(('\n'.join(rows)+'\n').encode())}

def dos_exe(b):
    if len(b)<64 or b[:2]!=b'MZ':raise ValueError('Native DOS MZ required')
    off=struct.unpack_from('<I',b,60)[0]
    if off<len(b) and b[off:off+2] in (b'PE',b'NE',b'LE',b'LX'):
        raise ValueError('DOS launcher cannot be a Windows executable')
    if len(b)>32768:raise ValueError('Unexpectedly large launcher')

def build(repo,watcom,out):
    if out.exists():raise ValueError('Fresh build directory required')
    driver=watcom/'binnt/wcl.exe'
    for n in ('binnt/wcl.exe','binnt/wcc.exe','binnt/wlink.exe','h/dos.h'):
        if not (watcom/n).is_file():raise ValueError('Complete Open Watcom DOS toolchain required: '+n)
    out.mkdir(parents=True)
    src=sources(repo)
    for n,b in src.items():save(out/n,b)
    env=dict(os.environ,WATCOM=str(watcom),INCLUDE=str(watcom/'h'))
    env['PATH']=str(watcom/'binnt')+os.pathsep+env.get('PATH','')
    command=[str(driver),'-zq','-bt=dos','-0','-ms','-os','-s','-k4096','-fm=FRESH.MAP','-fe=FRESH.EXE','FRESH.C']
    p=subprocess.run(command,cwd=out,env=env,stdout=subprocess.PIPE,stderr=subprocess.STDOUT)
    save(out/'BUILD.LOG',p.stdout)
    if p.returncode:raise ValueError('Native DOS build failed: '+p.stdout.decode(errors='replace'))
    b=(out/'FRESH.EXE').read_bytes();dos_exe(b)
    rec=dict(status='BUILT_NOT_RUNTIME_TESTED',base=BASE_PIN,sources={n:identity(b) for n,b in src.items()},
             binary=identity(b),compiler='Open Watcom native DOS, 8086 small model, 4096-byte stack',
             command=command,toolchain={n:identity((watcom/n).read_bytes()) for n in ('binnt/wcl.exe','binnt/wcc.exe','binnt/wlink.exe')})
    receipt(out/'FRESHBLD.JSN',rec);return rec

def archive(path,files):
    with zipfile.ZipFile(path,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
        for n,b in sorted(files.items()):
            info=zipfile.ZipInfo(n,(1980,1,1,0,0,0));info.compress_type=zipfile.ZIP_DEFLATED
            info.external_attr=0x20;z.writestr(info,b)

def pack(repo,built,out):
    if out.exists():raise ValueError('Fresh package directory required')
    rec=json.loads((built/'FRESHBLD.JSN').read_bytes());src=sources(repo)
    if rec['base']!=BASE_PIN or rec['sources']!={n:identity(b) for n,b in src.items()}:
        raise ValueError('Launcher build source/base differs')
    exe=(built/'FRESH.EXE').read_bytes();dos_exe(exe)
    if rec['binary']!=identity(exe):raise ValueError('Built launcher changed')
    original,fresh=inputs(repo);files=dict(original)
    files['CGAOLD.TXT']=files.pop('README.TXT')
    files['README.TXT']=crlf((HERE/'FRESH.TXT').read_bytes())
    files.update({'FRESH.EXE':exe,'FRESH.TXT':crlf((HERE/'FRESH.TXT').read_bytes()),
                  'FRESHLIC.TXT':crlf((HERE/'FRESHLIC.TXT').read_bytes()),
                  'OWATCOM.TXT':(repo/'tools/XR1PACK/OWATCOM.TXT').read_bytes()})
    files.update({'FRESH640/'+n:b for n,b in fresh.items()})
    assert all(files[n]==b for n,b in original.items() if n!='README.TXT')
    assert files['CGAOLD.TXT']==original['README.TXT']
    out.mkdir(parents=True)
    for n,b in files.items():save(out/'expanded'/n,b)
    archive(out/'CGAFRESH.ZIP',files)
    sourcefiles={'src/cga/'+n:(HERE/n).read_bytes() for n in ('FRESH.C','FRESH.INF','FRESH.TXT','FRESHLIC.TXT','FRESHPK.PY','FRESHT.PY')}
    sourcefiles['tools/DOSINST/CRCFAST.H']=(repo/'tools/DOSINST/CRCFAST.H').read_bytes()
    sourcefiles['tools/XR1PACK/OWATCOM.TXT']=(repo/'tools/XR1PACK/OWATCOM.TXT').read_bytes()
    sourcefiles[BASE]=(repo/BASE).read_bytes();archive(out/'CGAFSRC.ZIP',sourcefiles)
    result=dict(status='LOCAL_CANDIDATE_NATIVE_QUALIFICATION_SEPARATE',base=BASE_PIN,
                launcher=identity(exe),preserved_base_members=len(original)-1,original_readme_preserved_as='CGAOLD.TXT',fresh_profile='640x200 mono only',
                fresh_support={n:identity(b) for n,b in fresh.items()},
                files={n:identity(b) for n,b in files.items()},
                archives={n:identity((out/n).read_bytes()) for n in ('CGAFRESH.ZIP','CGAFSRC.ZIP')},
                os_files_included=False,tandy_changed=False,published=False)
    receipt(out/'CGAFRESH.JSN',result);return result

if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('action',choices=('build','pack'))
    ap.add_argument('--repo',type=Path,required=True);ap.add_argument('--out',type=Path,required=True)
    ap.add_argument('--watcom',type=Path);ap.add_argument('--build',type=Path);a=ap.parse_args()
    if a.action=='build':
        if not a.watcom:ap.error('--watcom required')
        result=build(a.repo.resolve(),a.watcom.resolve(),a.out.resolve())
    else:
        if not a.build:ap.error('--build required')
        result=pack(a.repo.resolve(),a.build.resolve(),a.out.resolve())
    print(json.dumps({k:v for k,v in result.items() if k in ('status','binary','launcher','archives')},indent=2))
