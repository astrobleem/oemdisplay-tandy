#!/usr/bin/env python3
"""Execute the driver's exact Plantronics conversion code under DOSBox-X.

Usage:
  python3 src/pcp/PCPTEST.PY --deps <DEPS.PY materialized inputs> \
      --dosbox <dosbox-x> --out <fresh-dir>
  python3 src/pcp/PCPTEST.PY --show --deps ... --dosbox ... --out <fresh-dir>

Test mode: generates PCPTEST.ASM from the same PCPPATCH text the driver
build inserts (pp_half/pp_byte macros, pp_spread table, CGA row address
block), assembles it with the pinned MASM 5.10 and LINK inside DOSBox-X
(8086 prefetch core), feeds it a seeded random 32,000-byte shadow (four
planes x 40 bytes x 200 rows) plus edge patterns, and has it convert the
whole frame into a RAM buffer, not B800h (DOSBox-X has no ColorPlus). The
host then checks every byte against the model and every one of the 64,000
pixels through the 86Box ColorPlus decode against the color the TR5 Tandy
flush would have shown.

--show builds PCPSHOW.EXE instead: the same code writing to B800h after
INT 10h mode 04h and port 3DDh = 10h, drawing 16 labelled-order color bars
until a key is pressed. That is for real ColorPlus-class hardware or an
86Box ColorPlus card; it cannot be judged in DOSBox-X.
"""
import argparse
import importlib.machinery
import json
import os
import random
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
P = importlib.machinery.SourceFileLoader("pcppatch", str(HERE / "PCPPATCH.PY")).load_module()


def asm_text(show):
    target = ("    mov ax,4\r\n    int 10h\r\n    mov dx,3ddh\r\n    mov al,10h\r\n    out dx,al\r\n"
              "    mov ax,0b800h\r\n    mov es,ax\r\n") if show else \
             ("    mov ax,vbuf\r\n    mov es,ax\r\n    xor di,di\r\n    mov cx,16384\r\n"
              "    xor ax,ax\r\n    cld\r\n    rep stosw\r\n")
    tail = ("    xor ah,ah\r\n    int 16h\r\n    mov dx,3ddh\r\n    xor al,al\r\n    out dx,al\r\n"
            "    mov ax,3\r\n    int 10h\r\n    mov ax,4c00h\r\n    int 21h\r\n") if show else \
           ("    push cs\r\n    pop ds\r\n    mov dx,offset fn_out\r\n    mov ah,3ch\r\n    xor cx,cx\r\n"
            "    int 21h\r\n    jc fail\r\n    mov bx,ax\r\n    mov ax,vbuf\r\n    mov ds,ax\r\n"
            "    xor dx,dx\r\n    mov cx,8000h\r\n    mov ah,40h\r\n    int 21h\r\n    jc fail\r\n"
            "    mov ah,3eh\r\n    int 21h\r\n    mov ax,4c00h\r\n    int 21h\r\n")
    return ("; Generated by src/pcp/PCPTEST.PY from PCPPATCH text. MASM 5.1, .8086.\r\n"
            ".8086\r\n"
            "stk segment stack 'STACK'\r\n    db 512 dup(?)\r\nstk ends\r\n"
            "shad segment para public 'SHAD'\r\n    db 32000 dup(?)\r\nshad ends\r\n"
            "vbuf segment para public 'VBUF'\r\n    db 32768 dup(?)\r\nvbuf ends\r\n"
            "code segment para public 'CODE'\r\n"
            "assume cs:code,ds:nothing,es:nothing\r\n"
            + P.CONVERT_MACROS + P.spread_table_text() +
            "fn_in db 'SHADOW.BIN',0\r\nfn_out db 'VRAM.BIN',0\r\n"
            "start:\r\n"
            "    push cs\r\n    pop ds\r\n    mov dx,offset fn_in\r\n    mov ax,3d00h\r\n    int 21h\r\n"
            "    jnc opened\r\n    jmp fail\r\nopened:\r\n    mov bx,ax\r\n    mov ax,shad\r\n    mov ds,ax\r\n    xor dx,dx\r\n"
            "    mov cx,32000\r\n    mov ah,3fh\r\n    int 21h\r\n    jc rdfail\r\n    cmp ax,32000\r\n"
            "    je rdok\r\nrdfail:\r\n    jmp fail\r\nrdok:\r\n    mov ah,3eh\r\n    int 21h\r\n"
            + target +
            "    mov ax,shad\r\n    mov ds,ax\r\n    cld\r\n    xor bp,bp\r\n    xor si,si\r\n"
            "frow:\r\n" + P.pcp_row_block("bp") +
            "    mov cx,40\r\nfbyte:\r\n    pp_byte\r\n    inc si\r\n    dec cx\r\n    jz fnext\r\n    jmp fbyte\r\nfnext:\r\n"
            "    add si,120\r\n    inc bp\r\n    cmp bp,200\r\n    jae fdone\r\n    jmp frow\r\nfdone:\r\n"
            + tail +
            "fail:\r\n    mov ax,4c01h\r\n    int 21h\r\ncode ends\r\nend start\r\n")


def make_shadow(show):
    sh = bytearray(32000)
    if show:
        # 16 vertical bars, 20 pixels each, color = bar index (IRGB).
        for y in range(200):
            for x in range(320):
                c = x // 20
                bits = ((c >> 2) & 1, (c >> 1) & 1, c & 1, (c >> 3) & 1)  # R,G,B,I
                for p, v in enumerate(bits):
                    if v:
                        sh[y * 160 + p * 40 + (x >> 3)] |= 0x80 >> (x & 7)
        return bytes(sh)
    rnd = random.Random(1987)
    sh = bytearray(rnd.randrange(256) for _ in range(32000))
    for y in (0, 1, 198, 199):           # edges: all-ones, all-zeros, alternating
        for xb in range(40):
            for p in range(4):
                sh[y * 160 + p * 40 + xb] = (0xFF, 0x00, 0xAA, 0x55)[(y + p) & 3]
    return bytes(sh)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--deps", type=Path, required=True)
    ap.add_argument("--dosbox", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--show", action="store_true")
    a = ap.parse_args()
    out = a.out.resolve()
    out.mkdir(parents=True, exist_ok=False)
    name = "PCPSHOW" if a.show else "PCPTEST"
    (out / (name + ".ASM")).write_bytes(asm_text(a.show).encode("ascii"))
    shadow = make_shadow(a.show)
    (out / "SHADOW.BIN").write_bytes(shadow)
    for tool in ("MASM.EXE", "LINK.EXE"):
        shutil.copy2(a.deps / "BIN" / tool, out / tool)
    run = [f"MASM {name};> MASM.LOG", f"LINK {name};> LINK.LOG"]
    if not a.show:
        run += [f"{name}.EXE", "IF ERRORLEVEL 1 echo RUN=FAIL> RUN.LOG",
                "IF NOT ERRORLEVEL 1 echo RUN=PASS> RUN.LOG"]
    conf = ("[sdl]\noutput=surface\n[dosbox]\nmachine=tandy\nmemsize=1\n[cpu]\ncore=normal\n"
            "cputype=8086_prefetch\ncycles=fixed 200000\n[mixer]\nnosound=true\n[autoexec]\n"
            f"mount c \"{out}\"\nc:\n" + "\n".join(run) + "\nexit\n")
    (out / "RUN.CONF").write_text(conf)
    env = dict(os.environ, SDL_VIDEODRIVER="dummy", SDL_AUDIODRIVER="dummy")
    with open(out / "HOST.LOG", "wb") as log:
        subprocess.run([str(a.dosbox), "-nopromptfolder", "-nogui", "-nomenu", "-conf",
                        str(out / "RUN.CONF")], env=env, stdout=log, stderr=subprocess.STDOUT,
                       timeout=300, check=True)
    for tool in ("MASM.EXE", "LINK.EXE"):
        (out / tool).unlink()
    masm = (out / "MASM.LOG").read_text(errors="replace")
    if " 0 Severe  Errors" not in masm.replace("\r", ""):
        raise SystemExit("PCPTEST: MASM reported errors; see MASM.LOG")
    if a.show:
        print(f"PCPTEST: built {out / 'PCPSHOW.EXE'} (run with SHADOW.BIN beside it)")
        return 0
    vram = (out / "VRAM.BIN").read_bytes()
    model = P.model_flush(shadow)
    byte_bad = sum(1 for i in range(0x8000) if vram[i] != model[i])
    pix_bad = sum(1 for y in range(200) for x in range(320)
                  if P.pcp_pixel(vram, y, x) != P.shadow_pixel(shadow, y, x))
    result = {"run": (out / "RUN.LOG").read_text().strip(), "vram_bytes": len(vram),
              "byte_mismatches_vs_model": byte_bad, "pixels_checked": 64000,
              "pixel_mismatches_vs_tr5_colors": pix_bad,
              "verdict": "PASS" if (byte_bad == 0 and pix_bad == 0) else "FAIL"}
    (out / "RESULT.JSN").write_text(json.dumps(result, indent=1) + "\n")
    print(json.dumps(result, indent=1))
    return 0 if result["verdict"] == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
