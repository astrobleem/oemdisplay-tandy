#!/usr/bin/env python3
"""8088 interrupt-safe replacement of REP plus source-segment MOVS overrides.

Run after MODEPROF (including MODECOL/MONOCOL), preserving all earlier pins.
An 8088 interrupted during multi-prefix REP may restart at the last prefix,
losing REP. JCXZ; segment:MOVS; LOOP has no multi-prefix instruction and keeps
FLAGS, DF, all segment registers, zero count and sequential overlap semantics.
Only staged sources change. Build success is not physical-hardware acceptance.
"""
from pathlib import Path
import hashlib, importlib.machinery, json, re, sys

# Normalized, exact post-MODEPROF inputs; no upstream pins are relaxed.
EXPECTED = {'320x200x16': {'CBLT.ASM': 'c29c238b411c5da98115157b522c9483db6bd86495dd72f266c2609af1ddbc3f', 'SPECIAL.INC': '39181b26565c8b39941a089236d64014178cb34013df32fce63d6be64441d4eb', 'BMC_ITE.ASM': 'aed252ef7b98acfdfc7f5166b6c129163d64a5e68ebe5d79e07fcc4babc4d782'}, '640x200x4': {'CBLT.ASM': '54ac17d45f5d5d3d564c1b5df8032f247eefd0b7af9609381f1ef56c002f1036', 'SPECIAL.INC': '39181b26565c8b39941a089236d64014178cb34013df32fce63d6be64441d4eb', 'BMC_ITE.ASM': '7c29c5920a9cf668bccb52a6dec05851f9e17bf9b66fa552170372a8af4c1a48'}, '160x200x16': {'CBLT.ASM': 'c29c238b411c5da98115157b522c9483db6bd86495dd72f266c2609af1ddbc3f', 'SPECIAL.INC': '39181b26565c8b39941a089236d64014178cb34013df32fce63d6be64441d4eb', 'BMC_ITE.ASM': 'aed252ef7b98acfdfc7f5166b6c129163d64a5e68ebe5d79e07fcc4babc4d782'}, '320x200x4': {'CBLT.ASM': '54ac17d45f5d5d3d564c1b5df8032f247eefd0b7af9609381f1ef56c002f1036', 'SPECIAL.INC': '39181b26565c8b39941a089236d64014178cb34013df32fce63d6be64441d4eb', 'BMC_ITE.ASM': '4aa4e91f94370fa891b9b06ba1f4fd6a48d83ce5bb27c5a56293c24275a84de0'}, '640x200x2': {'CBLT.ASM': '08b97016a7265cfe28398a4dab1e9fc5cb11d56ce2aa3fcd4d67c4832919b673', 'SPECIAL.INC': '39181b26565c8b39941a089236d64014178cb34013df32fce63d6be64441d4eb', 'BMC_ITE.ASM': '73d11a740a886ea536a6c74615c63d9553f554edfd3c2b9ff283e6a8743465a5'}}
COUNTS = {"CBLT.ASM": 9, "SPECIAL.INC": 1, "BMC_ITE.ASM": 1}
COMPILED_COUNTS = {"CBLT.LST": 8, "BITBLT.LST": 1, "BMC_ITE.LST": 1}
PREFIXES = {0x26, 0x2e, 0x36, 0x3e, 0xf0, 0xf2, 0xf3}
GENCONST_SHA = "03181aa20710f654422bba543e083f3c8bfacfbfcf24e5df035ae4c0cb9783e8"
EMITTER_SHA = "f16818de74cfa8de7251e39c8e2717164612dfec2e07a79bc815f71b467698f6"


def normalized(path):
    return Path(path).read_bytes().replace(b"\r\n", b"\n").replace(b"\x1a", b"").decode("latin1")


def sha(text):
    return hashlib.sha256(text.encode("latin1")).hexdigest()


def write_dos(path, text):
    Path(path).write_bytes(text.replace("\r\n", "\n").replace("\n", "\r\n").encode("latin1"))


def checked(path, expected):
    text = normalized(path)
    actual = sha(text)
    if actual != expected:
        raise RuntimeError(f"Unaudited REPCOPY88 input {path}: {actual}; expected {expected}")
    return text


def port(renderer, mode):
    renderer = Path(renderer)
    originals = {name: checked(renderer/name, pin) for name, pin in EXPECTED[mode].items()}
    checked(renderer/"GENCONST.INC", GENCONST_SHA)
    cblt = originals["CBLT.ASM"]
    # Audited dynamic REP has instruction boundaries B9 imm16 | F3 A5/AB.
    # The count immediate may itself contain prefix-looking bytes: do not grep
    # raw generated bytes for prefixes without decoding these boundaries.
    emitter = cblt[cblt.index("cblt_5100:\n"):cblt.index("cblt_5140:\n")]
    if sha(emitter) != EMITTER_SHA or len(re.findall(r"\bI_REP\b", cblt)) != 1:
        raise RuntimeError("Unaudited dynamic REP emitter")
    changed, sites = {}, []
    pattern = re.compile(r"^([ \t]*)rep[ \t]+(movs[ \t]+[^;\n]+?)([ \t]*(?:;[^\n]*)?)$", re.M | re.I)
    for name, original in originals.items():
        count = 0
        def one(match):
            nonlocal count
            count += 1
            indent, instruction, comment = match.groups()
            # Destination ES is implicit. Every pinned source override is CS/ES.
            if not re.search(r",[ \t]*(?:(?:byte|word)[ \t]+ptr[ \t]+|[bw]ptr[ \t]+)?(?:cs|es):\[si\]$", instruction, re.I):
                raise RuntimeError("Unexpected source override: " + instruction)
            label = "rc88_" + name.split(".")[0].lower() + "_" + str(count)
            sites.append({"file": name, "site": count, "original": match[0].strip(), "label": label})
            return (f"{indent}; REPCOPY88: interrupt-safe, flags/DF/zero count preserved.\n"
                    f"{indent}jcxz {label}_done\n{label}_copy:\n"
                    f"{indent}{instruction}{comment}\n{indent}loop {label}_copy\n{label}_done:")
        text = pattern.sub(one, original)
        if count != COUNTS[name]:
            raise RuntimeError(f"Expected {COUNTS[name]} overridden REP sites in {name}, found {count}")
        if name == "CBLT.ASM":
            old = "cblt_5140:\n\tjmp\tshort cblt_6000\t\t;Done setting up the innerloop"
            new = "cblt_5140:\n\tjmp\tcblt_6000\t\t;REPCOPY88 growth requires near branch"
            if text.count(old) != 1:
                raise RuntimeError("Expected one cblt_5140 short branch")
            text = text.replace(old, new)
        changed[name] = text
    # Validate every input and substitution before writing any stage file.
    for name, text in changed.items():
        write_dos(renderer/name, text)
    return {"feature": "8088 interrupt-safe overridden string copies", "mode": mode,
            "source_sites": sites, "source_site_count": len(sites),
            "compiled_site_count_expected": sum(COMPILED_COUNTS.values()),
            "dormant_site": "CBLT ninth source site is under IFDEF _BANK",
            "input_normalized_sha256": EXPECTED[mode],
            "output_normalized_sha256": {name: sha(text) for name, text in changed.items()},
            "branch_change": "cblt_5140 -> cblt_6000 widened from SHORT to near",
            "dynamic_rep_review": {"emitter_normalized_sha256": EMITTER_SHA,
                "genconst_normalized_sha256": GENCONST_SHA,
                "forms": ["B9 imm16; F3 A5", "B9 imm16; F3 AB"],
                "conclusion": "Single-prefix REP MOVSW/STOSW retained; segment overrides elsewhere attach ordinary loads/stores"},
            "contract": "JCXZ; one segment-override MOVSB/MOVSW; LOOP. Flags and other registers unchanged, CX/SI/DI and overlap behavior retained; no CLI"}


def instruction_rows(path):
    # AUDIT88 independently rejects every unclassified emitted instruction.
    isa = importlib.machinery.SourceFileLoader("repcopy_isa", str(Path(__file__).with_name("AUDIT88.PY"))).load_module()
    data_words = {"db", "dw", "dd", "dq", "dt", "bitmap", "bitmapinfoheader", "rgbquad", "rgbtriple", "bitmapcoreheader"}
    last = None
    for lineno, raw in enumerate(Path(path).read_text(errors="replace").splitlines(), 1):
        line = raw.expandtabs(8)
        if not re.match(r"^ [0-9A-F]{4}  [0-9A-F]{2}", line):
            continue
        source = line[32:].strip().split(";", 1)[0].strip()
        words = source.split()
        if words and words[0].endswith(":"):
            words = words[1:]
        if not words:
            continue
        mnemonic = words[0].lower()
        if mnemonic in data_words or (len(words)>1 and words[1].lower() in data_words) or mnemonic == "even":
            continue
        if mnemonic not in isa.MNEMONICS and mnemonic != "out16":
            raise AssertionError("Unclassified emitted listing row: " + line)
        tokens = re.findall(r"[0-9A-F]{2,8}", line[7:28])
        if not tokens:
            raise AssertionError("No machine bytes: " + line)
        address = int(line[1:5], 16)
        # MASM displays words in value order; prefix/opcode bytes are individual
        # tokens. Only leading bytes are decoded, never immediates/relocations.
        leading = []
        for token in tokens:
            leading.append(int(token[:2], 16))
            if len(token) != 2 or leading[-1] not in PREFIXES:
                break
        key = (address, tuple(tokens))
        if key == last:
            continue  # Macro invocation header may duplicate expansion bytes.
        last = key
        yield {"file": Path(path).name, "line": lineno, "address": address,
               "tokens": tokens, "leading": leading, "source": source}


def audit_listings(paths, require_replacements=True):
    bad, replacements, prefix_rows, single_rep, instructions = [], [], 0, 0, 0
    for path in paths:
        rows = list(instruction_rows(path))
        pending, pending_end = [], None
        for index, row in enumerate(rows):
            instructions += 1
            leading = row["leading"]
            if pending and row["address"] != pending_end:
                raise AssertionError("Noncontiguous standalone instruction prefixes: " + str(row))
            combined = pending + leading
            prefixes = []
            for value in combined:
                if value not in PREFIXES:
                    break
                prefixes.append(value)
            if any(value in (0xf2, 0xf3) for value in prefixes):
                if len(prefixes) > 1:
                    bad.append({**row, "prefixes": [f"{value:02X}" for value in prefixes]})
                elif len(combined) > len(prefixes):
                    single_rep += 1
            if len(combined) == len(prefixes):
                pending = combined
                pending_end = row["address"] + len(leading)
                prefix_rows += 1
                continue
            pending, pending_end = [], None
            if re.search(r"\bjcxz\s+rc88_\w+_done$", row["source"], re.I):
                triplet = rows[index:index+3]
                tokens = [value for item in triplet for value in item["tokens"]]
                if (len(triplet) != 3 or tokens[:2] != ["E3", "04"] or
                    tokens[2:4] not in (["26", "A4"], ["2E", "A4"], ["2E", "A5"]) or
                    tokens[4:] != ["E2", "FC"] or
                    [item["address"] for item in triplet] != [row["address"]+n for n in (0,2,4)]):
                    raise AssertionError("Unexpected REPCOPY88 machine code: " + str(triplet))
                replacements.append({"file": row["file"], "line": row["line"],
                    "address": f"{row['address']:04X}", "bytes": " ".join(tokens), "source": row["source"]})
        if pending:
            raise AssertionError("Unterminated standalone instruction prefix in " + str(path))
    counts = {name: sum(row["file"] == name for row in replacements) for name in COMPILED_COUNTS}
    report = {"instruction_rows_checked": instructions, "multi_prefix_rep": bad,
              "standalone_prefix_rows_checked": prefix_rows, "single_prefix_rep_retained": single_rep,
              "replacement_counts": counts, "replacement_sites": replacements,
              "scope": "Decoded emitted instruction prefixes across all linked listings, including adjacent standalone prefix rows; pinned dynamic emitter reviewed separately"}
    if bad or (require_replacements and counts != COMPILED_COUNTS):
        raise AssertionError(json.dumps(report, indent=2))
    return report


if __name__ == "__main__":
    print(json.dumps(audit_listings([Path(path) for path in sys.argv[1:]]), indent=2))
