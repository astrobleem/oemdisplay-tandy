SOURCES = {"T40PRES.ASM": HERE / "T40PRES.ASM", "T40DATA.ASM": HERE / "T40DATA.ASM"}


def fragment(name):
    """The exact fragment text the driver patch inserts (CRLF)."""
    data = SOURCES[name].read_bytes().decode("ascii")
    if "\n" in data.replace("\r\n", ""):
        raise SystemExit(f"T40TEST: {name} must use CRLF line ends")
    return data


def harness_text():
    geom = f"T40_COLS equ {COLS}\r\nT40_NROWS equ {ROWS}\r\nT40_SLOTB equ {SLOTB}\r\nT40_SNAPB equ 8192\r\n"
    t = HARNESS.replace("\r\n", "\n").replace("\n", "\r\n")
    t = t.replace("@@GEOM@@\r\n", geom).replace("@@SHBYTES@@", str(ROWB * H)).replace("@@TXTBYTES@@", str(2 * NCELL))
    return t.replace("@@DATA@@\r\n", fragment("T40DATA.ASM")).replace("@@PRES@@\r\n", fragment("T40PRES.ASM"))


# ---- scenes ------------------------------------------------------------------

class Scene:
    def __init__(self, ops, model):
        self.frame = bytearray(W * H)
        self.ops = ops
        self.model = model
        self.expect = []
        self.shadow = bytes(ROWB * H)
        self.flushed = bytearray(ROWB * H)   # shadow as covered by flushes so far

    def disciplined(self):
        """The driver flushes every pixel it changes; so must the scenes."""
        if bytes(self.flushed) != bytes(self.shadow):
            raise SystemExit("T40TEST: a scene changed pixels it never flushed")

    def fill(self, x0, y0, x1, y1, c):
        x0, y0, x1, y1 = max(x0, 0), max(y0, 0), min(x1, W), min(y1, H)
        for y in range(y0, y1):
            self.frame[y * W + x0:y * W + x1] = bytes([c]) * max(x1 - x0, 0)

    def dither(self, x0, y0, x1, y1, a, b):
        for y in range(max(y0, 0), min(y1, H)):
            for x in range(max(x0, 0), min(x1, W)):
                self.frame[y * W + x] = a if (x + y) & 1 else b

    def glyph(self, x, y, g, fg, bg, opaque=True, underline=False):
        for r in range(8):
            for c in range(8):
                xx, yy = x + c, y + r
                if 0 <= xx < W and 0 <= yy < H:
                    on = (g[r] >> (7 - c)) & 1 or (underline and r == 7)
                    if on:
                        self.frame[yy * W + xx] = fg
                    elif opaque:
                        self.frame[yy * W + xx] = bg

    def add(self, x, y, g, code):
        self.ops.append(struct.pack("<Bhh8sB", 1, x, y, bytes(g), code))
        self.model.add(x, y, g, code)

    def text(self, x, y, s, font, fg, bg, opaque=True, underline_at=None):
        for i, ch in enumerate(s):
            g = font[ch]
            self.glyph(x + 8 * i, y, g, fg, bg, opaque, i == underline_at and g[7] == 0)
            self.add(x + 8 * i, y, g, M.ansi_to_cp437(ch))

    def load(self):
        self.shadow = M.shadow_from_frame(self.frame)
        self.ops.append(bytes([4]) + bytes(self.shadow))

    def present(self, ay, by, cx, dx):
        self.ops.append(struct.pack("<Bhhhh", 3, ay, by, cx, dx))
        self.model.present(self.shadow, ay, by, cx, dx)
        self.expect.append(list(self.model.text))
        for y in range(max(ay, 0), min(by, H)):
            for p in range(4):
                o = y * ROWB + p * COLS
                self.flushed[o + max(cx, 0):o + min(dx, COLS)] = self.shadow[o + max(cx, 0):o + min(dx, COLS)]

    @staticmethod
    def clamp(ay, by, cx, dx):
        return max(ay, 0), min(by, H), max(cx, 0), min(dx, COLS)

    def snap(self, ay, by, cx, dx):
        ay, by, cx, dx = self.clamp(ay, by, cx, dx)
        if ay < by and cx < dx:
            self.ops.append(struct.pack("<Bhhhh", 7, ay, by, cx, dx))
            self.model.snap(self.shadow, ay, by, cx, dx)

    def present_diff(self, ay, by, cx, dx):
        ay, by, cx, dx = self.clamp(ay, by, cx, dx)
        if not (ay < by and cx < dx):
            return
        # probe: the expected buffer is 0FFFFh except the cells the diff
        # flush rewrites, so presenting more or fewer cells than the
        # specification is a mismatch even when the text would be the same
        self.ops.append(struct.pack("<Bhhhh", 10, ay, by, cx, dx))
        self.model.written = set()
        self.model.present_diff(self.shadow, ay, by, cx, dx)
        self.expect.append([w if k in self.model.written else 0xFFFF for k, w in enumerate(self.model.text)])
        for y in range(ay, by):
            for p in range(4):
                o = y * ROWB + p * COLS
                self.flushed[o + cx:o + dx] = self.shadow[o + cx:o + dx]

    def move(self, sx, sy, w, h, ddx, ddy):
        old = bytes(self.frame)
        for y in range(sy, sy + h):
            for x in range(sx, sx + w):
                tx, ty = x + ddx, y + ddy
                if 0 <= tx < W and 0 <= ty < H:
                    self.frame[ty * W + tx] = old[y * W + x]
        self.ops.append(struct.pack("<Bhhhhhh", 2, sx, sy, w, h, ddx, ddy))
        self.model.blit(sx, sy, w, h, ddx, ddy)


def synthetic(rnd, font, ops, model, n):
    s = Scene(ops, model)
    chars = [c for c in font if 33 <= c < 127] + [c for c in font if c >= 160]
    words = lambda k: [rnd.choice(chars) if rnd.random() > 0.15 else 32 for _ in range(k)]
    s.fill(0, 0, W, H, rnd.randrange(16))
    for _ in range(6):
        x0, y0 = rnd.randrange(-20, W), rnd.randrange(-20, H)
        s.fill(x0, y0, x0 + rnd.randrange(8, 160), y0 + rnd.randrange(8, 120), rnd.randrange(16))
    for _ in range(3):
        y = rnd.randrange(H)
        s.fill(rnd.randrange(W), y, W, y + 1, rnd.randrange(16))
        x = rnd.randrange(W)
        s.fill(x, rnd.randrange(H), x + 1, H, rnd.randrange(16))
    x0, y0 = rnd.randrange(W), rnd.randrange(H)
    s.dither(x0, y0, x0 + 40, y0 + 24, rnd.randrange(16), rnd.randrange(16))
    # text at every kind of alignment, including the screen edges
    spots = [(-4, -4), (-3, 0), (W - 8 - 8 * 3, H - 8), (W - 5 - 8 * 4, H - 5), (-1, 97)]
    spots += [(rnd.randrange(-4, W - 20), rnd.randrange(-4, H - 4)) for _ in range(n)]
    for (x, y) in spots:
        fg, bg = rnd.randrange(16), rnd.randrange(16)
        k = rnd.randrange(2, 12)
        opaque = rnd.random() > 0.2
        s.text(x, y, words(k), font, fg, bg, opaque, rnd.randrange(k) if rnd.random() < 0.3 else None)
    # every pixel density in two-colour cells (shade thresholds)
    for k in rnd.sample(range(NCELL), 64):
        cx, cy = k % COLS, k // COLS
        a, b = rnd.randrange(16), rnd.randrange(16)
        on = set(rnd.sample(range(64), rnd.randrange(65)))
        for i in range(64):
            s.frame[(8 * cy + i // 8) * W + 8 * cx + i % 8] = a if i in on else b
    # crossing lines in cells: every box-drawing junction
    for k in rnd.sample(range(NCELL), 48):
        cx, cy = k % COLS, k // COLS
        a, b = rnd.sample(range(16), 2)
        r, c = rnd.randrange(8), rnd.randrange(8)
        for i in range(64):
            on = i // 8 == r or i % 8 == c
            s.frame[(8 * cy + i // 8) * W + 8 * cx + i % 8] = a if on else b
    # glyphs at the screen edges, half with one wrong pixel at the window's
    # last on-screen column or row
    edge = [(x, y) for x in (-4, -3, -2, -1, W - 8, W - 7, W - 6, W - 5)
            for y in (rnd.randrange(-4, H - 4), rnd.choice((-4, -1, H - 8, H - 5)))]
    for (x, y) in edge:
        ch = rnd.choice(chars)
        fg, bg = rnd.sample(range(16), 2)
        s.glyph(x, y, font[ch], fg, bg)
        s.add(x, y, font[ch], M.ansi_to_cp437(ch))
        if rnd.random() < 0.5:
            xx = min(x + 7, W - 1) if rnd.random() < 0.5 else max(x, 0)
            yy = min(y + 7, H - 1) if rnd.random() < 0.5 else max(y, 0)
            s.frame[yy * W + xx] = rnd.randrange(16)
    s.load()
    s.present(0, H, 0, COLS)
    expect_ideal = [(len(s.expect) - 1, model.ideal(s.shadow))]
    # overpaint, partial flushes, more text, moves
    for step in range(8):
        s.disciplined()
        r = rnd.random()
        diff = rnd.random() < 0.5            # snapshot-diff flush instead
        if r < 0.3:
            x0, y0 = rnd.randrange(W), rnd.randrange(H)
            x1, y1 = x0 + rnd.randrange(1, 80), y0 + rnd.randrange(1, 50)
            rect = (y0, y1, x0 >> 3, (min(x1, W) + 7) >> 3)
            if diff:
                s.snap(*rect)
            s.fill(x0, y0, x1, y1, rnd.randrange(16))
            s.load()
            (s.present_diff if diff else s.present)(*rect)
        elif r < 0.55:
            x, y = rnd.randrange(-4, W - 20), rnd.randrange(-4, H - 4)
            k = rnd.randrange(1, 10)
            rect = (y, y + 8, max(x, 0) >> 3, (min(x + 8 * k, W) + 7) >> 3)
            if diff:
                s.snap(rect[0] - 8, rect[1] + 8, rect[2] - 2, rect[3] + 3)   # a wider rewrite
                rect = (rect[0] - 8, rect[1] + 8, rect[2] - 2, rect[3] + 3)
            s.text(x, y, words(k), font, rnd.randrange(16), rnd.randrange(16))
            s.load()
            (s.present_diff if diff else s.present)(*rect)
        elif r < 0.8:
            w, h = rnd.randrange(16, 200), rnd.randrange(16, 120)
            sx, sy = rnd.randrange(0, W - w + 1), rnd.randrange(0, H - h + 1)
            dx, dy = rnd.randrange(-sx, W - w - sx + 1), rnd.randrange(-sy, H - h - sy + 1)
            s.move(sx, sy, w, h, dx, dy)
            s.load()
            s.present(sy + dy, sy + dy + h, (sx + dx) >> 3, (sx + dx + w + 7) >> 3)
        else:
            y = rnd.randrange(H)
            s.frame[y * W + rnd.randrange(W)] = rnd.randrange(16)
            s.load()
            s.present(y, y + 1, 0, COLS)
    # nick one pixel of a shown glyph that lies in a neighbouring cell row or
    # column, flushing only that pixel: the hint's own cell must change
    shown = [k for k in range(NCELL) if model.shown(s.shadow, k)]
    for k in rnd.sample(shown, min(6, len(shown))):
        (x, y, g, c), _ = model.shown(s.shadow, k)
        cells = [(xx, yy) for yy in range(max(y, 0), min(y + 8, H)) for xx in range(max(x, 0), min(x + 8, W))
                 if (yy >> 3, xx >> 3) != (k // COLS, k % COLS)]
        if cells:
            xx, yy = rnd.choice(cells)
            s.frame[yy * W + xx] = (s.frame[yy * W + xx] + rnd.randrange(1, 16)) % 16
            s.load()
            s.present(yy, yy + 1, xx >> 3, (xx >> 3) + 1)
    # a hint recorded for pixels already on screen, then a flush beside it
    # whose output range holds its cell but whose pixels do not touch it:
    # the cell must still be re-verified (stale), not keep its old state
    x, y = 8 * rnd.randrange(3, COLS - 3), 8 * rnd.randrange(1, ROWS - 2)
    ch = rnd.choice(chars)
    s.fill(x - 16, y - 8, x + 16, y + 16, 7)
    s.glyph(x, y, font[ch], 0, 7)
    s.load()
    s.present(y - 8, y + 16, (x >> 3) - 2, (x >> 3) + 2)
    s.add(x, y, font[ch], M.ansi_to_cp437(ch))
    s.present(y, y + 1, (x >> 3) - 1, x >> 3)
    # a focused button label: a dotted line through rows 0 and 7 of the
    # glyphs; and an underscore whose line was painted over
    x, y = 8 * rnd.randrange(2, COLS - 10) + rnd.randrange(8), 8 * rnd.randrange(1, ROWS - 3) + rnd.randrange(8)
    s.fill(x - 8, y - 8, x + 40, y + 16, 15)
    s.text(x, y, [ord(c) for c in "OK_A"], font, 0, 15)
    for c in range(x - 1, x + 33, 2):
        for yy in (y, y + 7):
            s.frame[yy * W + c] = 0 if s.frame[yy * W + c] == 15 else 15
    s.fill(x + 16, y + 7, x + 24, y + 8, 15)
    s.load()
    s.present(y - 8, y + 16, (x >> 3) - 1, (x >> 3) + 6)
    # same position redrawn: the newer hint replaces, the older one in that
    # cell survives, and comes back when its pixels are restored
    x, y = 8 * rnd.randrange(1, COLS - 2) + 2, 8 * rnd.randrange(1, ROWS - 2) + 1
    old, new1, new2 = rnd.sample(chars, 3)
    s.fill(x - 8, y - 8, x + 16, y + 16, 1)
    s.glyph(x - 2, y - 1, font[old], 14, 1)
    s.add(x - 2, y - 1, font[old], M.ansi_to_cp437(old))
    saved = bytes(s.frame)
    s.glyph(x, y, font[new1], 15, 4)
    s.add(x, y, font[new1], M.ansi_to_cp437(new1))
    s.glyph(x, y, font[new2], 15, 4)
    s.add(x, y, font[new2], M.ansi_to_cp437(new2))
    s.load()
    s.present(y - 8, y + 16, (x >> 3) - 1, (x >> 3) + 3)
    s.frame = bytearray(saved)
    s.load()
    s.present(y - 8, y + 16, (x >> 3) - 1, (x >> 3) + 3)
    s.disciplined()
    s.present(0, H, 0, COLS)
    expect_ideal.append((len(s.expect) - 1, model.ideal(s.shadow)))
    return s.expect, expect_ideal


BENCH = [  # (name, ay, by, cx, dx, repeats)
    ("full screen", 0, 200, 0, None, 4),
    ("one text line (8 rows, full width)", 96, 104, 0, None, 16),
    ("menu item (10 rows, 12 columns)", 70, 80, 4, 16, 16),
    ("caret (1 column, 10 rows)", 50, 60, 9, 10, 64),
]


# ---- review regressions with explicit expected cells -------------------------
# Each returns (expect, ideal checks, explicit checks); an explicit check is
# (flush index within the scene, cell, kind, code): kind "is" = the cell shows
# that code, "not" = it does not. They are checked on the model when the
# scene is built (a failure there is a specification bug) and on every
# presenter text buffer.
P = (83, 81)        # a glyph window not aligned to the grid; holding cell (10, 10)
Q = (78, 79)        # another position whose window centre is in the same cell


def cell10():
    return 10 * COLS + 10


def _blank(s):
    s.fill(0, 0, W, H, 1)
    s.load()
    s.present(0, H, 0, COLS)


def _flush_cell(s):
    s.load()
    s.present(72, 96, 8, 13)        # the cell and its neighbours, every glyph pixel


def regression_same_position(font, ops, model):
    """A then B drawn at the same position: B replaces A's hint. B is shown;
    when A's pixels come back without a new hint (a bitmap restore), neither
    the stale B nor the replaced A may be shown."""
    s = Scene(ops, model)
    _blank(s)
    checks = []
    for ch in "AB":
        s.glyph(*P, font[ord(ch)], 15, 1)
        s.add(*P, font[ord(ch)], ord(ch))
        _flush_cell(s)
        checks.append((len(s.expect) - 1, cell10(), "is", ord(ch)))
    s.glyph(*P, font[ord("A")], 15, 1)      # pixels only, no hint
    _flush_cell(s)
    checks += [(len(s.expect) - 1, cell10(), "not", ord("B")), (len(s.expect) - 1, cell10(), "not", ord("A"))]
    return s.expect, [(len(s.expect) - 1, model.ideal(s.shadow))], checks


def regression_two_positions(font, ops, model):
    """A at P, then X at Q over it (same cell, another position): X is shown;
    when A's pixels are restored (a closing menu), A comes back from the
    second slot."""
    s = Scene(ops, model)
    _blank(s)
    s.glyph(*P, font[ord("A")], 15, 1)
    s.add(*P, font[ord("A")], ord("A"))
    _flush_cell(s)
    s.glyph(*Q, font[ord("X")], 14, 1)
    s.add(*Q, font[ord("X")], ord("X"))
    _flush_cell(s)
    checks = [(len(s.expect) - 1, cell10(), "is", ord("X"))]
    s.fill(Q[0], Q[1], Q[0] + 8, Q[1] + 8, 1)
    s.glyph(*P, font[ord("A")], 15, 1)
    _flush_cell(s)
    checks.append((len(s.expect) - 1, cell10(), "is", ord("A")))
    return s.expect, [(len(s.expect) - 1, model.ideal(s.shadow))], checks


def regression_partial_overpaint(font, ops, model):
    """H is shown, then part of its window is overpainted and only that part
    is flushed: the hint is stale and must not be shown. Cases: the left
    half in the background colour, the top four rows in another colour,
    one ink pixel, one background pixel set to the ink colour."""
    out_expect, out_ideal, checks = [], [], []
    g = font[ord("H")]
    ink = [(r, c) for r in range(8) for c in range(8) if (g[r] >> (7 - c)) & 1]
    paper = [(r, c) for r in range(1, 7) for c in range(8) if not (g[r] >> (7 - c)) & 1]
    cases = [("left half", [(r, c, 1) for r in range(8) for c in range(4)]),
             ("top rows", [(r, c, 4) for r in range(4) for c in range(8)]),
             ("one ink pixel", [(ink[len(ink) // 2][0], ink[len(ink) // 2][1], 1)]),
             ("one paper pixel", [(paper[0][0], paper[0][1], 15)])]
    for name, pix in cases:
        s = Scene(ops, model.__class__())
        ops.append(bytes([5]))
        _blank(s)
        s.glyph(*P, g, 15, 1)
        s.add(*P, g, ord("H"))
        _flush_cell(s)
        base = len(out_expect)
        checks.append((base + len(s.expect) - 1, cell10(), "is", ord("H")))
        for r, c, col in pix:
            s.frame[(P[1] + r) * W + P[0] + c] = col
        rows = [P[1] + r for r, _, _ in pix]
        cols = [(P[0] + c) >> 3 for _, c, _ in pix]
        s.load()
        s.present(min(rows), max(rows) + 1, min(cols), max(cols) + 1)    # only the overpainted part
        checks.append((base + len(s.expect) - 1, cell10(), "not", ord("H")))
        s.present(0, H, 0, COLS)
        checks.append((base + len(s.expect) - 1, cell10(), "not", ord("H")))
        out_ideal.append((base + len(s.expect) - 1, s.model.ideal(s.shadow)))
        out_expect += s.expect
    return out_expect, out_ideal, checks


def regression_diff_flush(font, ops, model):
    """Snapshot-diff flushes. (1) A wide rectangle rewritten with identical
    pixels changes nothing. (2) Typing one glyph into a wide opaque line:
    the glyph is shown. (3) A hint recorded for pixels already on screen,
    inside a rectangle whose pixels do not change: the cell is stale and
    must show the glyph. (4) A snapshot of one rectangle, then a flush of
    another: an ordinary flush."""
    s = Scene(ops, model)
    _blank(s)
    checks = []
    s.glyph(*P, font[ord("Q")], 15, 1)
    s.add(*P, font[ord("Q")], ord("Q"))
    _flush_cell(s)
    before = list(s.model.text)
    s.snap(64, 112, 0, COLS)
    s.fill(0, 64, W, 112, 1)                     # identical rewrite, then the glyph again
    s.glyph(*P, font[ord("Q")], 15, 1)
    s.add(*P, font[ord("Q")], ord("Q"))
    s.load()
    s.present_diff(64, 112, 0, COLS)
    checks.append((len(s.expect) - 1, cell10(), "is", ord("Q")))
    if s.model.text != before:
        fail(EXIT_BUILD, "T40TEST: specification: an identical rewrite changed the text")
    x2 = P[0] + 8
    s.snap(P[1], P[1] + 8, 0, COLS)
    s.glyph(x2, P[1], font[ord("R")], 15, 1)
    s.add(x2, P[1], font[ord("R")], ord("R"))
    s.load()
    s.present_diff(P[1], P[1] + 8, 0, COLS)
    checks.append((len(s.expect) - 1, cell10() + 1, "is", ord("R")))
    # (3) pixels first (flushed with no hint), then the hint alone
    x3 = P[0] + 16
    s.glyph(x3, P[1], font[ord("S")], 15, 1)
    s.load()
    s.present(P[1], P[1] + 8, (x3 >> 3), (x3 >> 3) + 2)
    checks.append((len(s.expect) - 1, cell10() + 2, "not", ord("S")))
    s.snap(P[1], P[1] + 8, 0, COLS)
    s.add(x3, P[1], font[ord("S")], ord("S"))
    s.present_diff(P[1], P[1] + 8, 0, COLS)
    checks.append((len(s.expect) - 1, cell10() + 2, "is", ord("S")))
    # (4) a hint made stale just left of and above the flushed rectangle,
    # for pixels already on screen: the cell is in the output range and
    # must show the glyph although none of the rectangle's pixels change
    xl, yl = 8 * 20 + 2, 8 * 15 + 1
    s.glyph(xl, yl, font[ord("L")], 15, 1)
    s.load()
    s.present(yl, yl + 8, xl >> 3, (xl >> 3) + 2)
    s.snap(8 * 16, 8 * 18, 21, 30)
    s.add(xl, yl, font[ord("L")], ord("L"))
    s.present_diff(8 * 16, 8 * 18, 21, 30)
    checks.append((len(s.expect) - 1, 15 * COLS + 20, "is", ord("L")))
    # (5) a snapshot of another rectangle, then pixels changed (no hint)
    # inside the flushed one: an ordinary flush; the stale Q must go
    s.snap(0, 8, 0, 4)
    s.fill(P[0], P[1], P[0] + 8, P[1] + 8, 4)
    s.load()
    s.present_diff(64, 112, 0, COLS)
    checks.append((len(s.expect) - 1, cell10(), "not", ord("Q")))
    # (6) mismatched rectangles
    s.snap(0, 8, 0, 4)
    s.glyph(x3 + 8, P[1], font[ord("T")], 15, 1)
    s.add(x3 + 8, P[1], font[ord("T")], ord("T"))
    s.load()
    s.present_diff(P[1], P[1] + 8, 0, COLS)
    checks.append((len(s.expect) - 1, cell10() + 3, "is", ord("T")))
    s.present(0, H, 0, COLS)                     # probe buffers hold 0FFFFh: compare a full one
    return s.expect, [(len(s.expect) - 1, model.ideal(s.shadow))], checks


def regression_blit_overlap(font, ops, model):
    """Screen-to-screen copies that overlap their source (scrolling, window
    moves by less than their size): three rows of text moved down by one
    text row and right by one cell must show the same three rows at the new
    place, each hint moved once (the copy order matters: down/right copies
    must take the bottom/right cells first)."""
    s = Scene(ops, model)
    _blank(s)
    rows = ["ABC", "DEF", "GHI"]
    x0, y0 = 16, 40
    for r, word in enumerate(rows):
        s.text(x0, y0 + 8 * r, [ord(c) for c in word], font, 15, 1)
    s.load()
    s.present(y0, y0 + 24, x0 >> 3, (x0 >> 3) + 3)
    s.move(x0, y0, 24, 24, 8, 8)
    s.load()
    s.present(y0, y0 + 32, x0 >> 3, (x0 >> 3) + 4)
    k = len(s.expect) - 1
    checks = []
    for r, word in enumerate(rows):
        for c, ch in enumerate(word):
            cell = ((y0 >> 3) + 1 + r) * COLS + (x0 >> 3) + 1 + c
            checks.append((k, cell, "is", ord(ch)))
    return s.expect, [(k, model.ideal(s.shadow))], checks


REGRESSIONS = (regression_same_position, regression_two_positions, regression_partial_overpaint,
               regression_diff_flush, regression_blit_overlap)


def explicit_ok(text, cell, kind, code):
    shown = text[cell] & 0xFF
    return shown == code if kind == "is" else shown != code


def bench_scene(rnd, font, ops, model):
    """A desktop-like screen: wallpaper bars, a window with a title, a menu
    bar and lines of text, then the BENCH flushes, timed by the guest."""
    s = Scene(ops, model)
    for x in range(W):
        s.fill(x, 0, x + 1, H, x // 20)
    s.fill(24, 16, W - 8, 192, 15)
    s.fill(24, 16, W - 8, 26, 1)
    chars = [c for c in font if 33 <= c < 127]
    s.text(120, 17, [ord(c) for c in "Program Manager"], font, 15, 1)
    s.text(32, 28, [ord(c) for c in "File  Options  Window  Help"], font, 0, 15)
    s.fill(24, 37, W - 8, 38, 0)
    for k in range(14):
        s.text(32, 42 + 10 * k, [rnd.choice(chars) for _ in range(COLS - 10)], font, 0, 15)
    s.load()
    s.present(0, H, 0, COLS)
    for name, ay, by, cx, dx, n in BENCH:
        ops.append(struct.pack("<Bhhhhh", 6, ay, by, cx, COLS if dx is None else dx, n))
    return s.expect, [(0, model.ideal(s.shadow))]


def frame_scene(path, ops, model):
    from PIL import Image
    frame = Image.open(path).tobytes()
    fonts = [(ROOT / "distributions" / "WINXT" / "XTTSYS.FON", False),
             (ROOT / "distributions" / "WINXT" / "XTCOEM.FON", True)]
    s = Scene(ops, model)
    s.frame = bytearray(frame)
    for h in M.oracle_hints(frame, fonts):
        s.add(*h)
    s.load()
    s.present(0, H, 0, COLS)
    return s.expect, [(0, model.ideal(s.shadow))]


# Exit codes (T40MUT relies on them): 0 the presenter equals the model;
# 1 the comparison ran and found a difference (a detected fault);
# 3 the presenter or harness did not assemble or link (a tool/build
# failure, never a detected fault); 4 the harness itself failed (emulator
# exit, timeout, no output to compare).
EXIT_DIFF, EXIT_BUILD, EXIT_HARNESS = 1, 3, 4


def fail(code, message):
    print(message, file=sys.stderr)
    sys.exit(code)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--deps", type=Path, required=True)
    ap.add_argument("--dosbox", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--frames", type=Path)
    ap.add_argument("--scenes", type=int, default=6)
    ap.add_argument("--pres", type=Path, help="alternative T40PRES.ASM (mutation runs)")
    ap.add_argument("--cols", type=int, default=40, choices=(40, 80),
                    help="text columns: 40 (TXT40, 320x200 shadow) or 80 (TEXT80, 640x200)")
    ap.add_argument("--slot", type=int, default=None, choices=(16, 14),
                    help="hint slot bytes (default 16 for 40 columns, 14 for 80)")
    ap.add_argument("--bench", action="store_true",
                    help="only the timed desktop scene; T40TEST.EXE + OPS.BIN also run on an XT")
    a = ap.parse_args()
    geometry(a.cols, a.slot or (16 if a.cols == 40 else 14))
    if a.pres:
        SOURCES["T40PRES.ASM"] = a.pres
    out = a.out.resolve()
    out.mkdir(parents=True, exist_ok=False)
    (out / "T40TEST.ASM").write_bytes(harness_text().encode("ascii"))
    font = F.glyphs(ROOT / "distributions" / "WINXT" / "XTTSYS.FON")
    font = {c: g for c, g in font.items()}
    rnd = random.Random(4025)
    ops, expect, ideal_checks, names = [], [], [], []
    for i in range(0 if a.bench else a.scenes):
        model = M.Presenter()
        ops.append(bytes([5]))
        base = len(expect)
        e, ideal = synthetic(rnd, font, ops, model, 10 + 4 * i)
        expect += e
        ideal_checks += [(base + k, t) for k, t in ideal]
        names += [f"synthetic{i}"] * len(e)
    explicit = []
    for fn in ([] if a.bench else REGRESSIONS):
        model = M.Presenter()
        ops.append(bytes([5]))
        base = len(expect)
        e, ideal, checks = fn(font, ops, model)
        for k, cell, kind, code in checks:
            if not explicit_ok(e[k], cell, kind, code):
                fail(EXIT_BUILD, f"T40TEST: specification fails regression {fn.__name__}: flush {k}, "
                                 f"cell {cell} {kind} {code:#x}, model shows {e[k][cell]:#06x}")
        expect += e
        ideal_checks += [(base + k, t) for k, t in ideal]
        explicit += [(fn.__name__, base + k, cell, kind, code) for k, cell, kind, code in checks]
        names += [fn.__name__] * len(e)
    if a.bench:
        model = M.Presenter()
        ops.append(bytes([5]))
        e, ideal = bench_scene(rnd, font, ops, model)
        expect += e
        ideal_checks += [(k, t) for k, t in ideal]
        names += ["bench"] * len(e)
    if a.frames:
        for p in sorted(a.frames.glob("*.png")):
            model = M.Presenter()
            ops.append(bytes([5]))
            base = len(expect)
            e, ideal = frame_scene(p, ops, model)
            expect += e
            ideal_checks += [(base + k, t) for k, t in ideal]
            names += [p.stem] * len(e)
    ops.append(bytes([0]))
    (out / "OPS.BIN").write_bytes(b"".join(ops))
    for tool in ("MASM.EXE", "LINK.EXE"):
        shutil.copy2(a.deps / "BIN" / tool, out / tool)
    run = ["MASM T40TEST;> MASM.LOG", "LINK T40TEST;> LINK.LOG", "T40TEST.EXE",
           "IF ERRORLEVEL 1 echo RUN=FAIL> RUN.LOG", "IF NOT ERRORLEVEL 1 echo RUN=PASS> RUN.LOG"]
    conf = ("[sdl]\noutput=surface\n[dosbox]\nmachine=cga\nmemsize=1\n[cpu]\ncore=normal\n"
            "cputype=8086_prefetch\ncycles=max\n[mixer]\nnosound=true\n[autoexec]\n"
            f"mount c \"{out}\"\nc:\n" + "\n".join(run) + "\nexit\n")
    (out / "RUN.CONF").write_text(conf)
    env = dict(os.environ, SDL_VIDEODRIVER="dummy", SDL_AUDIODRIVER="dummy")
    try:
        with open(out / "HOST.LOG", "wb") as log:
            rc = subprocess.run([str(a.dosbox), "-nopromptfolder", "-nogui", "-nomenu", "-conf",
                                 str(out / "RUN.CONF")], env=env, stdout=log, stderr=subprocess.STDOUT,
                                timeout=1800).returncode
    except subprocess.TimeoutExpired:
        rc = "timeout"
    for tool in ("MASM.EXE", "LINK.EXE"):
        (out / tool).unlink()
    masm = (out / "MASM.LOG").read_text(errors="replace") if (out / "MASM.LOG").exists() else ""
    link = (out / "LINK.LOG").read_text(errors="replace") if (out / "LINK.LOG").exists() else ""
    if re.findall(r"(\d+)\s+Severe\s+Errors", masm) != ["0"]:
        print(masm)
        fail(EXIT_BUILD, "T40TEST: MASM did not report 0 severe errors; see MASM.LOG")
    if re.search(r"error L\d+|fatal error", link, re.I) or not (out / "T40TEST.EXE").is_file():
        print(link)
        fail(EXIT_BUILD, "T40TEST: LINK failed; see LINK.LOG")
    if rc != 0:
        fail(EXIT_HARNESS, f"T40TEST: emulator exited {rc}; see HOST.LOG")
    run_log = (out / "RUN.LOG").read_text(errors="replace").strip() if (out / "RUN.LOG").exists() else ""
    if run_log not in ("RUN=PASS", "RUN=FAIL"):
        fail(EXIT_HARNESS, "T40TEST: the test program did not run to its end (no RUN.LOG); see HOST.LOG")
    got = (out / "TEXT.BIN").read_bytes() if (out / "TEXT.BIN").exists() else b""
    tb = 2 * NCELL
    dumps = [list(struct.unpack(f"<{NCELL}H", got[i:i + tb])) for i in range(0, len(got) - tb + 1, tb)]
    bad = []
    for i, want in enumerate(expect):
        if i >= len(dumps):
            bad.append({"flush": i, "scene": names[i], "problem": "missing"})
            continue
        diff = [k for k in range(NCELL) if dumps[i][k] != want[k]]
        if diff:
            k = diff[0]
            bad.append({"flush": i, "scene": names[i], "cells": len(diff), "first": k,
                        "got": hex(dumps[i][k]), "want": hex(want[k])})
    ideal_bad = sum(1 for i, t in ideal_checks if i >= len(dumps) or dumps[i] != t)
    explicit_bad = [{"regression": n, "flush": i, "cell": c, "kind": k, "code": code,
                     "shown": dumps[i][c] if i < len(dumps) else None}
                    for n, i, c, k, code in explicit if i >= len(dumps) or not explicit_ok(dumps[i], c, k, code)]
    ticks = (out / "TIME.BIN").read_bytes() if (out / "TIME.BIN").exists() else b""
    result = {"run": run_log or "missing", "flushes": len(expect), "dumps": len(dumps),
              "geometry": f"{COLS}x{ROWS}, {SLOTB}-byte slots",
              "cells_compared": NCELL * len(expect), "mismatched_flushes": bad[:20],
              "full_flush_vs_ideal_failures": ideal_bad,
              "explicit_regression_checks": len(explicit), "explicit_failures": explicit_bad,
              "timed_flushes_here": len(ticks) // 2,
              "verdict": "PASS" if (run_log == "RUN=PASS" and not bad and not ideal_bad and not explicit_bad
                                    and len(dumps) == len(expect)) else "FAIL"}
    (out / "RESULT.JSN").write_text(json.dumps(result, indent=1) + "\n")
    print(json.dumps(result, indent=1))
    return 0 if result["verdict"] == "PASS" else EXIT_DIFF


if __name__ == "__main__":
    sys.exit(main())
