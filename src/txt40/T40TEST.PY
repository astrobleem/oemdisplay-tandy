#!/usr/bin/env python3
"""Execute the driver's exact TXT40 presenter code under DOSBox-X.

  python3 src/txt40/T40TEST.PY --deps <DEPS.PY materialized inputs> \
      --dosbox <dosbox-x> --out <fresh-dir> [--frames <dir of 320x200 PNGs>]

Assembles T40PRES.ASM and T40DATA.ASM, byte for byte the text T40PATCH.PY
inserts into the driver, into a DOS harness (pinned MASM 5.10 and LINK, run
in DOSBox-X on the 8086 prefetch core). The harness replays OPS.BIN:
hint additions, screen-to-screen hint moves, whole-shadow loads and flush
rectangles, writing the 40x25 text buffer (2000 bytes, RAM not B800h)
after every flush. The host replays the same operations through
T40MODEL.Presenter and requires every text buffer to be identical, and the
final full flush of each scene to equal Presenter.ideal().

Scenes are seeded and synthetic: rectangles, lines, dither, and text in
the first-party 8x8 system font at every alignment including the screen
edges, opaque, transparent and underlined, then overpainted, moved and
partly flushed. --frames adds decoded reference screenshots (kept outside
the repository) with hints found by T40MODEL.oracle_hints.
"""
