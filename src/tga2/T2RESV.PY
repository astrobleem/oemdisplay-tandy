#!/usr/bin/env python3
"""T2RESV.COM: keep the Tandy Video II page out of DOS, and its DOS tests.

  python3 src/tga2/T2RESV.PY --gen                 write T2RESV.ASM/T2RESVT.ASM only
  python3 src/tga2/T2RESV.PY --dosbox <dosbox-x> --out <new dir> [--repo <view>]
  ... --mutate stale_handles|no_gate      reintroduce one fixed defect; exit 0
                                          only if its checks FAIL (caught)

On the Tandy 1000 SL2 (86Box with owner-supplied BIOS ROMs, docs/TGA2.MD),
the 640x200x16 page is the top 64KB of the 640KB shared RAM, physical
90000h-9FFFFh. The BIOS keeps only 9C000h-9FFFFh from DOS (it reports
624KB), so 90000h-9BFFFh (48KB, 0C00h paragraphs) must be kept from DOS
before Windows starts, exactly as RESERVE.COM keeps the 16KB mode-09
overlap at 98000h-9BFFFh.

T2RESV.ASM is RESERVE.ASM (src/tandysw, unchanged and still the shipped
helper) with only the reserved range and the texts changed, applied as
exact substitutions with counts: target segment 9800h -> 9000h, its MCB
97FFh -> 8FFFh, paragraphs 400h -> 0C00h, signature TNDYRS01 -> TNDYV2R1.
Every check of the original stays (Tandy signature, BIOS 624KB, text mode
3, DOS 3+, the real arena ending at 9C00h, last-fit allocation verified to
the paragraph, no MCB edits, fail closed). T2RESVT.ASM is RESERVET.ASM with
its exact-occupation case moved the same way.

The DOS cases (DOSBox-X machine=tandy: 640KB, BIOS 624KB, arena to 9C00h
like the SL2) mirror RESERVE.PY: normal install, repeat, three allocation
strategies, occupied top and occupied exact range, RESERVE.COM's own 16KB
reservation already present, short arena, wrong BIOS size, wrong mode,
expanded memory, CGA, DOS 2.11. Results: <out>/RESULT.JSON.
"""
import argparse
import hashlib
import importlib.machinery
import json
import re
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TANDYSW = HERE.parent / "tandysw"
R = importlib.machinery.SourceFileLoader("reserve_harness", str(TANDYSW / "RESERVE.PY")).load_module()

HEADER = (
    "; T2RESV.ASM - GENERATED by src/tga2/T2RESV.PY from src/tandysw/RESERVE.ASM.\r\n"
    "; Do not edit; change the generator. Keeps the Tandy Video II 640x200x16\r\n"
    "; page out of DOS: physical 90000h-9BFFFh (0C00h paragraphs, MCB at\r\n"
    "; 8FFFh); the BIOS already excludes 9C000h-9FFFFh. Every check of\r\n"
    "; RESERVE.ASM is kept; only the range and the texts differ.\r\n")

SUBS = [  # (pattern, replacement, expected count) on RESERVE.ASM
    (r"cmp ax,9800h", "cmp ax,9000h", 2),
    (r"mov resident_video,9800h", "mov resident_video,9000h", 1),
    (r"cmp word ptr es:\[resident_video\],9800h", "cmp word ptr es:[resident_video],9000h", 1),
    (r"97ffh", "8fffh", 3),
    (r",400h\b", ",0C00h", 5),
    (r"'TNDYRS01'", "'TNDYV2R1'", 1),
    (r"terminal block starting at 9800h", "terminal block starting at 9000h", 1),
    (r"ES=97FFh top MCB", "ES=8FFFh top MCB", 1),
    (r"RESERVE: 16K video overlap reserved\.", "T2RESV: 48K Video II page reserved.", 1),
    (r"RESERVE: video reservation already installed\.", "T2RESV: Video II reservation already installed.", 1),
    (r"db 'RESERVE: ", "db 'T2RESV: ", 7),
    (r"top video overlap already occupied", "Video II page already occupied", 1),
]
TEST_SUBS = [
    (r"mov hog_size,400h", "mov hog_size,0C00h", 1),
    (r"mov hog_expect,9800h", "mov hog_expect,9000h", 1),
    # The snapshot counts the resident's open handles only when the last
    # block is the reservation; with RESERVE's 97FFh/400h left here the
    # count was never taken and "handles closed" passed vacuously.
    (r"cmp last_mcb,97ffh\r\n jne no_jft\r\n cmp last_size,400h",
     "cmp last_mcb,8fffh\r\n jne no_jft\r\n cmp last_size,0C00h", 1),
    # 'P' is RESERVE's mode-09 alias probe (physical 9800h); it does not
    # apply to the Video II page. 'P' now fails and the probe is removed.
    (r" cmp al,'P'\r\n JFAIL je,probe\r\n", " cmp al,'P'\r\n JFAIL je,bad\r\n", 1),
    (r"(?s)\r\nprobe:\r\n.*?\r\nbad_video:\r\n mov ax,3\r\n int 10h\r\n", "\r\n", 1),
]
TEST_HEADER = (
    "; T2RESVT.ASM - GENERATED by src/tga2/T2RESV.PY from src/tandysw/RESERVET.ASM.\r\n"
    "; Do not edit; change the generator. DOS regression probe for T2RESV: the\r\n"
    "; reservation is MCB 8FFFh, 0C00h paragraphs; RESERVE's mode-09 alias probe\r\n"
    "; ('P') is removed and fails.\r\n")


def generate(src, subs, header, leftovers=("9800h", "97ffh", "tndyrs01", ",400h")):
    text = src.read_bytes().decode("ascii")
    for pat, rep, want in subs:
        n = len(re.findall(pat, text))
        if n != want:
            raise SystemExit(f"T2RESV: {pat!r} matched {n} times in {src.name}, expected {want}")
        text = re.sub(pat, rep, text)
    lines = text.split("\r\n")
    # replace the leading comment block (lines starting with ';') by HEADER
    k = 0
    while k < len(lines) and lines[k].startswith(";"):
        k += 1
    if not header:
        return text
    text = header + "\r\n".join(lines[k:])
    # nothing of the old range left
    for left in leftovers:
        if left in text.lower():
            raise SystemExit(f"T2RESV: {left} left in the generated {src.name}")
    return text


MUTATIONS = {
    # T2RESVT counting handles at RESERVE's old 97FFh/400h block again
    "stale_handles": ["handle count is taken on a block at 8FFFh/0C00h (foreign resident: open handles seen)"],
    # T2SHOW without its reservation gate
    "no_gate": [f"T2SHOW gate {n}: exit 3, nothing touched"
                for n in ("show_unreserved", "show_foreign_exact", "show_reserve16", "show_short_arena")],
}


def write_sources(out, show=False, mutate=None):
    (out / "T2RESV.ASM").write_bytes(generate(TANDYSW / "RESERVE.ASM", SUBS, HEADER).encode("ascii"))
    subs, left = TEST_SUBS, ("9800h", "97ffh", ",400h", "cmp last_size,400h", "probe:", "bad_video")
    if mutate == "stale_handles":
        subs = [s for s in TEST_SUBS if "last_mcb" not in s[0]]
        left = ("9800h", "probe:", "bad_video")
    t = generate(TANDYSW / "RESERVET.ASM", subs, TEST_HEADER, leftovers=left)
    (out / "T2RESVT.ASM").write_bytes(t.encode("ascii"))
    if not show:
        return
    T = importlib.machinery.SourceFileLoader("t2test", str(HERE / "T2TEST.PY")).load_module()
    gate = T.NO_GATE if mutate == "no_gate" else T.GATE
    (out / "T2SHOW.ASM").write_bytes(T.generate(gate).encode("ascii"))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gen", action="store_true", help="write T2RESV.ASM and T2RESVT.ASM beside this script")
    ap.add_argument("--repo", type=Path, help="DDK view with BIN/MASM.EXE etc. (default: the repository)")
    ap.add_argument("--dosbox", type=Path)
    ap.add_argument("--out", type=Path)
    ap.add_argument("--mutate", choices=sorted(MUTATIONS))
    a = ap.parse_args()
    if a.gen:
        write_sources(HERE)
        print("T2RESV: wrote T2RESV.ASM, T2RESVT.ASM")
        return 0
    if not (a.dosbox and a.out):
        ap.error("--dosbox and --out are required (or --gen)")
    repo = (a.repo or HERE.parents[1]).resolve()
    out = a.out.resolve()
    out.mkdir(parents=True)
    write_sources(out, show=True, mutate=a.mutate)
    shutil.copyfile(TANDYSW / "RESERVE.ASM", out / "RESERVE.ASM")
    cmds = "@ECHO OFF\n"
    for n in ("T2RESV", "T2RESVT", "RESERVE", "T2SHOW"):
        cmds += (f"C:\\BIN\\MASM {n}.ASM,{n}.OBJ,{n}.LST; >> BUILD.LOG\n"
                 f"C:\\BIN\\LINK {n}.OBJ,{n}.EXE,{n}.MAP; >> BUILD.LOG\n"
                 f"C:\\DDK\\TOOLS\\EXE2BIN {n}.EXE {n}.COM >> BUILD.LOG\n")
    R.dos_text(out / "BUILD.BAT", cmds + "EXIT\n")
    R.run_dos(a.dosbox, repo, out, "BUILD.BAT")
    log = (out / "BUILD.LOG").read_text(errors="replace")
    if re.findall(r"(\d+)\s+Severe\s+Errors", log) != ["0"] * 4 or re.search(r"error [AL]\d+|fatal", log, re.I):
        raise SystemExit("T2RESV: assembly/link failed; see BUILD.LOG")
    # T2SHOW's gate reads T2RESV's resident record at PSP offset 103h.
    lst = (out / "T2RESV.LST").read_text(errors="replace")
    if not re.search(r"(?m)^\s*0103\s.*\bresident_id db 8 dup\(0\)", lst):
        raise SystemExit("T2RESV: resident_id is not at offset 103h; T2SHOW's gate would read the wrong place")
    checks, details, fails = [], {}, []

    def check(name, ok):
        print(("ok   " if ok else "FAIL ") + name)
        (checks if ok else fails).append(name)

    def case(name, commands, **settings):
        d = out / name
        d.mkdir()
        for b in ("T2RESV.COM", "T2RESVT.COM", "RESERVE.COM", "T2SHOW.COM"):
            shutil.copyfile(out / b, d / b)
        R.dos_text(d / "TEST.BAT", "@ECHO OFF\n" + commands + "EXIT\n")
        R.run_dos(a.dosbox, repo, d, "TEST.BAT", **settings)
        return d

    cap = lambda c, l: R.captured(c, l)
    snap = lambda l: R.captured("T2RESVT S", l) + f"COPY SNAP.BIN {l}.BIN > NUL\n"
    rep = R.report
    ret = R.returned

    d = case("normal", snap("BEFORE") + cap("T2RESV", "INSTALL") + snap("AFTER") +
             cap("T2RESV", "AGAIN") + snap("TWICE"))
    before, after, twice = rep(d, "BEFORE"), rep(d, "AFTER"), rep(d, "TWICE")
    details["normal"] = dict(before=before, after=after, twice=twice)
    check("normal 640K installs successfully", ret(d, "INSTALL") == 0)
    check("BIOS 624K unchanged, arena still ends at 9C00h",
          before["bda_kb"] == after["bda_kb"] == 624 and before["arena_end"] == after["arena_end"] == 0x9c00)
    check("the Video II page is one DOS block: MCB 8FFFh, 0C00h paragraphs, last, owned",
          after["last_mcb"] == 0x8fff and after["last_size"] == 0xc00 and
          after["last_type"] & 255 == ord("Z") and after["last_owner"] != 0)
    check("resident closes inherited handles", after["owner_open_handles"] == 0)
    check("repeated invocation succeeds without a second TSR",
          ret(d, "AGAIN") == 0 and after == twice and "already installed" in (d / "AGAIN.TXT").read_text())

    for s in (0, 1, 2):
        d = case(f"strategy{s}", cap(f"T2RESVT {s + 1}", "SET") + cap("T2RESV", "INSTALL") + snap("AFTER"))
        st = rep(d, "AFTER")
        details[f"strategy{s}"] = st
        check(f"allocation strategy {s} preserved, page reserved",
              ret(d, "INSTALL") == 0 and st["strategy"] == s and st["last_mcb"] == 0x8fff)

    for name, setup, text in (("occupied", "T2RESVT O", "already occupied"),
                              ("occupied_exact", "T2RESVT T", "already occupied"),
                              ("reserve16_first", "RESERVE", "already occupied")):
        d = case(name, cap(setup, "SETUP") + snap("BEFORE") + cap("T2RESV", "INSTALL") + snap("AFTER"))
        b, af = rep(d, "BEFORE"), rep(d, "AFTER")
        details[name] = dict(before=b, after=af)
        stable = ("last_mcb", "last_owner", "last_size", "arena_end", "bda_kb", "strategy")
        if name == "occupied_exact":
            # Liveness of the handle count: this foreign 9000h/0C00h resident
            # (T2RESVT T, a TSR) keeps its inherited handles open, so the
            # snapshot must see them. With a stale address it reads 0.
            check("handle count is taken on a block at 8FFFh/0C00h (foreign resident: open handles seen)",
                  b["last_mcb"] == 0x8fff and b["last_size"] == 0xc00 and b["owner_open_handles"] > 0)
        check(f"{name}: fails without taking another owner's memory",
              ret(d, "SETUP") == 0 and ret(d, "INSTALL") == 1 and all(b[k] == af[k] for k in stable) and
              text in (d / "INSTALL.TXT").read_text())

    for name, setup, settings in (("short_arena", "T2RESVT A\n", {}), ("wrong_bda", "T2RESVT B\n", {}),
                                  ("wrong_mode", "T2RESVT M\n", {}), ("expanded", "", dict(expanded=True)),
                                  ("cga", "", dict(machine="cga")), ("dos2", "", dict(version="2.11"))):
        d = case(name, setup + cap("T2RESV", "INSTALL") + snap("AFTER"), **settings)
        st = rep(d, "AFTER")
        details[name] = st
        check(f"{name}: fails closed", ret(d, "INSTALL") == 1 and st["last_owner"] == 0 and
              "No reservation" in (d / "INSTALL.TXT").read_text())

    # T2SHOW's gate: without T2RESV's own reservation it must refuse (exit 3)
    # before any video access; behind T2RESV it must pass. /G stops after
    # the gate, so these run on DOSBox-X, which has no Video II.
    def show_ret(d, label):
        return int((d / (label + ".RET")).read_text().strip())

    def show(label):
        return (f"T2SHOW /G > {label}.TXT\nIF ERRORLEVEL 4 GOTO X{label}\nIF ERRORLEVEL 3 GOTO R{label}\n"
                f"IF ERRORLEVEL 1 GOTO X{label}\nECHO 0> {label}.RET\nGOTO N{label}\n"
                f":R{label}\nECHO 3> {label}.RET\nGOTO N{label}\n:X{label}\nECHO 9> {label}.RET\n:N{label}\n")

    for name, setup, want, text in (
            ("show_unreserved", "", 3, "no T2RESV reservation"),
            ("show_foreign_exact", cap("T2RESVT T", "SETUP"), 3, "no T2RESV reservation"),
            ("show_reserve16", cap("RESERVE", "SETUP"), 3, "no T2RESV reservation"),
            ("show_short_arena", "T2RESVT A\n", 3, "no T2RESV reservation"),
            ("show_reserved", cap("T2RESV", "SETUP"), 0, "reservation found")):
        d = case(name, setup + snap("BEFORE") + show("SHOW") + snap("AFTER"))
        b, af = rep(d, "BEFORE"), rep(d, "AFTER")
        details[name] = dict(before=b, after=af)
        ok = (show_ret(d, "SHOW") == want and text in (d / "SHOW.TXT").read_text() and
              all(b[k] == af[k] for k in ("last_mcb", "last_owner", "last_size", "arena_end", "bda_kb")))
        if (d / "SETUP.RET").exists():          # the setup itself must have worked
            ok = ok and ret(d, "SETUP") == 0
        check(f"T2SHOW gate {name}: exit {want}" + (", nothing touched" if want else ""), ok)

    res = dict(status="PASS" if not fails else "FAIL", passed=len(checks), failed=fails, checks=checks,
               details=details, emulator="DOSBox-X machine=tandy (640K, BIOS 624K), not cycle-accurate",
               t2resv_bytes=(out / "T2RESV.COM").stat().st_size,
               t2resv_sha256=hashlib.sha256((out / "T2RESV.COM").read_bytes()).hexdigest(),
               t2show_bytes=(out / "T2SHOW.COM").stat().st_size,
               t2show_sha256=hashlib.sha256((out / "T2SHOW.COM").read_bytes()).hexdigest())
    if a.mutate:
        want = MUTATIONS[a.mutate]
        res["mutation"] = a.mutate
        res["caught"] = all(w in fails for w in want)
        res["status"] = "CAUGHT" if res["caught"] else "MISSED"
        print(f"T2RESV: mutation {a.mutate} " + res["status"])
    (out / "RESULT.JSON").write_text(json.dumps(res, indent=2) + "\n")
    print(json.dumps({k: res[k] for k in ("status", "passed", "t2resv_bytes", "t2resv_sha256", "t2show_sha256")}))
    if a.mutate:
        return 0 if res["caught"] else 1
    return 0 if not fails else 1


if __name__ == "__main__":
    sys.exit(main())
