# Original accent compositing. Lowercase reserves its two top blank rows;
# capitals are redrawn onto five rows so accents stay within the 8px cell.
import unicodedata
ACCENTS = {'\u0300': ('#....', '.#...'),
           '\u0301': ('....#', '...#.'),
           '\u0302': ('..#..', '.#.#.'),
           '\u0303': ('.#...', '#.#..'),
           '\u0308': ('.#.#.', '.....'),
           '\u030a': ('.###.', '.#.#.'),
           '\u030c': ('.#.#.', '..#..'),
           '\u0327': ('.....', '.#...')}


def accented(char):
    parts = unicodedata.normalize('NFD', char)
    if len(parts) != 2 or parts[0] not in G or parts[1] not in ACCENTS:
        return
    base, accent = G[parts[0]], parts[1]
    sw = max(5, len(base[0]))
    base = [row.center(sw, '.') for row in base]
    mask = [row.center(sw, '.') for row in ACCENTS[accent]]
    if accent == '\u0327':
        rows = base[:7] + [mask[1]]
    elif parts[0].isupper():
        rows = mask + [base[y] for y in (0, 1, 3, 5, 6)] + ['.' * sw]
    else:
        # Dotless i leaves the accent visually independent.
        if parts[0] == 'i':
            base[0] = '.' * sw
        rows = mask + base[2:]
    G[char] = rows


for code in list(range(0xc0, 0x100)) + [0x160, 0x161, 0x17d, 0x17e, 0x178]:
    accented(chr(code))

